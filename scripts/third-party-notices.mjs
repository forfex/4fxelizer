// Generates THIRD_PARTY_NOTICES.md: the libraries bundled into the renderer (the only third-party code
// that ships in the app besides Electron itself), with their licenses.
// Usage: node scripts/third-party-notices.mjs   (run after npm install; re-run when these dependencies change)
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOTS = ['react', 'react-dom', 'three', 'radix-ui', 'dockview-react', 'zustand', 'clsx', 'class-variance-authority', 'tailwind-merge', '@fontsource/chakra-petch', '@fontsource/rubik', '@fontsource/martian-mono']

const read = (dir, file) => (existsSync(join(dir, file)) ? readFileSync(join(dir, file), 'utf8') : null)
const pkgDir = (name) => join('node_modules', name)

const seen = new Map()
const visit = (name) => {
  if (seen.has(name)) return
  const dir = pkgDir(name)
  if (!existsSync(dir)) return // optional / platform specific
  const pkg = JSON.parse(read(dir, 'package.json'))
  seen.set(name, pkg)
  for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.peerDependencies })) visit(dep)
}
ROOTS.forEach(visit)
// peer dependencies pull in build-only packages; only keep what is actually needed at runtime
for (const n of [...seen.keys()]) if (n.startsWith('@types/')) seen.delete(n)

const licenseText = (name) => {
  const dir = pkgDir(name)
  const file = readdirSync(dir).find((f) => /^(licen[sc]e|copying)(\.|$)/i.test(f))
  return file ? read(dir, file).trim() : null
}

const entries = [...seen.entries()].sort(([a], [b]) => a.localeCompare(b))
const missing = entries.filter(([n]) => !licenseText(n)).map(([n]) => n)
const groups = new Map() // license text -> package list
for (const [name, pkg] of entries) {
  const text = licenseText(name) ?? `License: ${pkg.license} (no license file in the package)`
  if (!groups.has(text)) groups.set(text, [])
  groups.get(text).push(`${name}@${pkg.version} (${pkg.license})`)
}

let out = `# Third-party notices

4FXELIZER itself is MIT licensed (see LICENSE). The app bundles the open-source libraries listed below, and runs
inside Electron, whose own license and the Chromium license notices ship with every installer
(\`LICENSE.electron.txt\` and \`LICENSES.chromium.html\`). Everything else in \`package.json\` is a build or test
tool and is not distributed.

This file is generated by \`scripts/third-party-notices.mjs\`.

`
for (const [text, pkgs] of groups) {
  out += `## ${pkgs.join(', ')}\n\n\`\`\`\n${text}\n\`\`\`\n\n`
}
writeFileSync('THIRD_PARTY_NOTICES.md', out)
console.log(`${entries.length} packages, ${groups.size} distinct license texts`)
if (missing.length) console.log('no license file:', missing.join(', '))
